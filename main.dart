  Widget _buildTurnDashboard(
    GameState s,
    PlayerModel me,
    PlayerModel? activeP,
    bool isMyTurn,
    int reqCards,
  ) {
    Color borderColor = AppColors.blue;
    if (isMyTurn) borderColor = AppColors.green;
