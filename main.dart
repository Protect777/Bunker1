final Random _rng = Random();

class _TierChoice {
  final String key;
  final int score;
  const _TierChoice(this.key, this.score);
}

_TierChoice pickWeightedTier() {
  // 40 + 80 + 120 + 80 + 40 = 360
  final r = _rng.nextDouble() * 360.0;
  if (r < 40) return const _TierChoice('t_2', -2);
  if (r < 120) return const _TierChoice('t_1', -1);
  if (r < 240) return const _TierChoice('t0', 0);
  if (r < 320) return const _TierChoice('t1', 1);
  return const _TierChoice('t2', 2);
}

List<T> shuffleList<T>(List<T> items) {
  final copy = List<T>.from(items);
  copy.shuffle(_rng);
  return copy;
}

class DrawnTrait {
  final String value;
  final int tier;
  const DrawnTrait({required this.value, required this.tier});
}

List<DrawnTrait> drawGraduatedTraits(
  String categoryKey,
  int count,
  String mode, [
  List<String> customList = const [],
]) {
  final source = mode == 'fantasy'
      ? kFantasyGraded[categoryKey]!
      : kGradedTraits[categoryKey]!;
  final used = <String>{};
  final result = <DrawnTrait>[];

  for (final cText in customList) {
    if (result.length < count && !used.contains(cText)) {
      result.add(DrawnTrait(value: cText, tier: 1));
      used.add(cText);
    }
  }

  int guard = 0;
  while (result.length < count && guard < 500) {
    guard++;
    var tierObj = pickWeightedTier();
    if (mode == 'serious' && tierObj.key == 't_2' && _rng.nextDouble() < 0.5) {
      tierObj = const _TierChoice('t_1', -1);
    }
    if (mode == 'meme' && tierObj.key == 't0' && _rng.nextDouble() < 0.5) {
      tierObj = _rng.nextDouble() < 0.5
          ? const _TierChoice('t_2', -2)
          : const _TierChoice('t_1', -1);
    }

    final pool = source[tierObj.key] ?? source['t0']!;
    final candidate = pool[_rng.nextInt(pool.length)];
    if (!used.contains(candidate)) {
      used.add(candidate);
      result.add(DrawnTrait(value: candidate, tier: tierObj.score));
    }
  }
  return shuffleList(result);
}

DrawnTrait drawSingleByTier(String categoryKey, int minTier, String mode) {
  final source = mode == 'fantasy'
      ? kFantasyGraded[categoryKey]!
      : kGradedTraits[categoryKey]!;
  final key = minTier >= 2
      ? 't2'
      : minTier == 1
          ? 't1'
          : minTier <= -2
              ? 't_2'
              : 't_1';
  final pool = source[key] ?? source['t1']!;
  return DrawnTrait(
    value: pool[_rng.nextInt(pool.length)],
    tier: minTier,
  );
}

