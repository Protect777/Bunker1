      final t = shuffleList(enemies)[0];
      final temp = p.traits[3];
      p.traits[3] = t.traits[3];
      t.traits[3] = temp;
      state!.lastEvent = '🔄 ${p.name} обменялся Хобби с ${t.name}!';
    } else if (id == 'swap_health' && enemies.isNotEmpty) {
      final t = shuffleList(enemies)[0];
      final temp = p.traits[2];
      p.traits[2] = t.traits[2];
      t.traits[2] = temp;
      p.traits[2].revealed = true;
      t.traits[2].revealed = true;
      state!.lastEvent = '🧬 ${p.name} обменялся картой Здоровья с ${t.name}!';
    } else if (id == 'upgrade_hobby') {
      final c = drawSingleByTier('hobby', 2, m);
      p.traits[3] = TraitCard(
          label: p.traits[3].label, value: c.value, tier: 2, revealed: true);
      state!.lastEvent = '🛠️ ${p.name} освоил мастер-навык: ${c.value}!';
    } else if (id == 'cleanse_fact') {
      final c = drawSingleByTier('fact', 2, m);
      p.traits[5] = TraitCard(
          label: p.traits[5].label, value: c.value, tier: 2, revealed: true);
      state!.lastEvent = '🌟 ${p.name} открыл героический факт: ${c.value}!';
