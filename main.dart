// СЕТЕВОЙ КЛИЕНТ ПО 4-ЗНАЧНОМУ PIN-КОДУ (ЧИСТЫЙ DART: MQTT ПОВЕРХ WEBSOCKET)
// Работает между любыми устройствами в интернете без внешних нативных плагинов
// ============================================================================
class PinRoomNetworkClient {
  static const List<String> _brokers = [
    'wss://broker.emqx.io:8084/mqtt',
    'wss://broker.hivemq.com:8884/mqtt',
  ];

  WebSocket? _ws;
  Timer? _pingTimer;
  final String clientId;
  final String pin;
  final bool isHost;
  final void Function(Map<String, dynamic> message) onMessage;
  final void Function(String error)? onError;
  final VoidCallback? onConnected;

  PinRoomNetworkClient({
    required this.clientId,
    required this.pin,
    required this.isHost,
    required this.onMessage,
    this.onError,
    this.onConnected,
  });

  String get _hostTopic => 'bunker_v3_room/$pin/to_host';
  String get _stateTopic => 'bunker_v3_room/$pin/state';

  Future<void> connect() async {
    for (final url in _brokers) {
      try {
        _ws = await WebSocket.connect(
          url,
          protocols: ['mqtt'],
        ).timeout(const Duration(seconds: 6));

        _ws!.listen(
          _onRawData,
          onError: (_) {},
          onDone: () {},
        );

        // Отправляем пакет MQTT CONNECT (v3.1.1)
        _sendMqttConnect(clientId);

        // Подписываемся на нужный канал комнаты по 4-значному PIN-коду
        final subTopic = isHost ? _hostTopic : _stateTopic;
        await Future<void>.delayed(const Duration(milliseconds: 250));
        _sendMqttSubscribe(subTopic);

        _pingTimer?.cancel();
        _pingTimer = Timer.periodic(const Duration(seconds: 25), (_) {
          _sendRaw([0xC0, 0x00]); // MQTT PINGREQ
        });

        onConnected?.call();
        return;
      } catch (_) {
        // Пробуем резервный брокер
      }
    }
    onError?.call('Не удалось подключиться к сетевому серверу комнат');
  }

  void sendToHost(Map<String, dynamic> actionPayload) {
    _sendMqttPublish(_hostTopic, jsonEncode(actionPayload));
  }

  void broadcastState(GameState state) {
    _sendMqttPublish(_stateTopic, jsonEncode(state.toJson()));
  }

  void dispose() {
    _pingTimer?.cancel();
    try {
      _ws?.close();
    } catch (_) {}
    _ws = null;
  }

  void _sendRaw(List<int> bytes) {
    if (_ws != null && _ws!.readyState == WebSocket.open) {
      _ws!.add(Uint8List.fromList(bytes));
    }
  }

  List<int> _encodeRemainingLength(int length) {
    final encoded = <int>[];
    var rem = length;
    do {
      var byte = rem % 128;
      rem = rem ~/ 128;
      if (rem > 0) byte |= 128;
      encoded.add(byte);
    } while (rem > 0);
    return encoded;
  }

  void _sendMqttConnect(String id) {
    final idBytes = utf8.encode(id);
    final varHeader = <int>[
      0x00, 0x04, 0x4D, 0x51, 0x54, 0x54, // 'MQTT'
      0x04, // Protocol level 4 (3.1.1)
      0x02, // Clean session
      0x00, 0x3C, // Keepalive 60s
    ];
    final payload = <int>[
      (idBytes.length >> 8) & 0xFF,
      idBytes.length & 0xFF,
      ...idBytes,
    ];
    final remLen = _encodeRemainingLength(varHeader.length + payload.length);
    _sendRaw([0x10, ...remLen, ...varHeader, ...payload]);
  }

  void _sendMqttSubscribe(String topic) {
    final tBytes = utf8.encode(topic);
    final varHeader = <int>[0x00, 0x01]; // Packet ID = 1
    final payload = <int>[
      (tBytes.length >> 8) & 0xFF,
      tBytes.length & 0xFF,
      ...tBytes,
      0x00, // QoS 0
    ];
    final remLen = _encodeRemainingLength(varHeader.length + payload.length);
    _sendRaw([0x82, ...remLen, ...varHeader, ...payload]);
  }

  void _sendMqttPublish(String topic, String jsonStr) {
    final tBytes = utf8.encode(topic);
    final pBytes = utf8.encode(jsonStr);
    final varHeader = <int>[
      (tBytes.length >> 8) & 0xFF,
      tBytes.length & 0xFF,
      ...tBytes,
    ];
    final remLen = _encodeRemainingLength(varHeader.length + pBytes.length);
    _sendRaw([0x30, ...remLen, ...varHeader, ...pBytes]);
  }

  void _onRawData(dynamic raw) {
    List<int> data;
    if (raw is List<int>) {
      data = raw;
    } else if (raw is String) {
      data = utf8.encode(raw);
    } else {
      return;
    }

    int offset = 0;
    while (offset < data.length) {
      final headerByte = data[offset];
      final packetType = headerByte & 0xF0;

      int multiplier = 1;
      int remLength = 0;
      int idx = offset + 1;
      if (idx >= data.length) break;

      int encodedByte;
      do {
        if (idx >= data.length) return;
        encodedByte = data[idx++];
        remLength += (encodedByte & 127) * multiplier;
        multiplier *= 128;
      } while ((encodedByte & 128) != 0);

      final packetEnd = idx + remLength;
      if (packetEnd > data.length) break;

      if (packetType == 0x30) {
        // MQTT PUBLISH
        final topicLen = (data[idx] << 8) | data[idx + 1];
        var payloadStart = idx + 2 + topicLen;
        final qos = (headerByte >> 1) & 0x03;
        if (qos > 0) payloadStart += 2;

        if (payloadStart <= packetEnd) {
          final payloadBytes = data.sublist(payloadStart, packetEnd);
          try {
            final decodedStr = utf8.decode(payloadBytes);
            final decodedJson =
                jsonDecode(decodedStr) as Map<String, dynamic>;
            onMessage(decodedJson);
          } catch (_) {}
        }
      }
      offset = packetEnd;
    }
  }
}

