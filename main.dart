  void hostStartGame() {
    if (!isHost || state == null) return;
    if (state!.players.length < 4) {
      showToast('Нужно минимум 4 игрока (нажмите + Боты)!');
      return;
    }

    final n = state!.players.length;
    final m = state!.mode;
    final isFan = m == 'fantasy';

    final profs = drawGraduatedTraits('prof', n, m, state!.customCards);
    final bios = drawGraduatedTraits('bio', n, m);
    final healths = drawGraduatedTraits('health', n, m);
    final hobbies = drawGraduatedTraits('hobby', n, m);
    final luggages = drawGraduatedTraits('luggage', n, m);
    final facts = drawGraduatedTraits('fact', n, m);
    final actions = shuffleList(kActionCards);

    final scenPool = isFan ? kScenarios['fantasy']! : kScenarios['modern']!;
    state!.catastrophe = shuffleList(scenPool)[0];

    state!.bunker = BunkerInfo(
      time: shuffleList(
          isFan ? kBunkerData['fantasyTimes']! : kBunkerData['times']!)[0],
      rooms: shuffleList(
          isFan ? kBunkerData['fantasyRooms']! : kBunkerData['rooms']!)[0],
      supplies: shuffleList(isFan
          ? kBunkerData['fantasySupplies']!
          : kBunkerData['supplies']!)[0],
      issue: shuffleList(
          isFan ? kBunkerData['fantasyIssues']! : kBunkerData['issues']!)[0],
    );

    state!.capacity = n ~/ 2;
    state!.bunkerBonus = 0;
    state!.round = 1;
    state!.status = 'GAME';
    state!.votes = {};
    state!.rps = null;

    for (int i = 0; i < state!.players.length; i++) {
      final p = state!.players[i];
      p.exiled = false;
      p.actionUsed = false;
      p.voteShield = false;
      p.doubleVote = false;
      p.action = actions[i % actions.length];
      p.traits = [
        TraitCard(
          label: isFan ? 'Класс' : 'Профессия',
          value: profs[i].value,
          tier: profs[i].tier,
        ),
        TraitCard(
          label: isFan ? 'Раса и Возраст' : 'Биология',
          value: bios[i].value,
          tier: bios[i].tier,
        ),
        TraitCard(
          label: isFan ? 'Проклятие / Здоровье' : 'Здоровье',
          value: healths[i].value,
          tier: healths[i].tier,
        ),
        TraitCard(
          label: isFan ? 'Ремесло / Навык' : 'Хобби',
          value: hobbies[i].value,
          tier: hobbies[i].tier,
        ),
        TraitCard(
          label: isFan ? 'Артефакт / Инвентарь' : 'Багаж',
          value: luggages[i].value,
          tier: luggages[i].tier,
        ),
        TraitCard(
          label: isFan ? 'Тайна героя' : 'Особый факт',
          value: facts[i].value,
          tier: facts[i].tier,
        ),
      ];
    }

    state!.turnOrder = state!.players.map((p) => p.id).toList();
    state!.currentTurnIdx = 0;
    state!.cardsRequired = 1;
    state!.cardsOpenedInTurn = 0;

    final firstP = getActivePlayer();
    state!.lastEvent =
        '🔔 Раунд 1 начался! Первым ходит ${firstP != null ? firstP.name : ''}.';
    currentTab = 0;
    broadcastState();
    checkBotTurn();
  }

  void hostFinishVoting() {
    if (!isHost || state == null) return;
    final tally = <String, int>{};

    state!.votes.forEach((voterId, targetId) {
      final voter = state!.players.where((p) => p.id == voterId).firstOrNull;
      final weight = (voter != null && voter.doubleVote) ? 2 : 1;
      tally[targetId] = (tally[targetId] ?? 0) + weight;
    });

    for (final p in state!.players) {
      if (p.voteShield && tally.containsKey(p.id)) {
        tally[p.id] = max(0, tally[p.id]! - 1);
      }
    }

    int maxV = -1;
    for (final cnt in tally.values) {
      if (cnt > maxV) maxV = cnt;
    }

    if (maxV <= 0) {
      showToast('Ещё никто не проголосовал!');
      return;
    }

    final tiedIds =
        tally.keys.where((id) => tally[id] == maxV).toList();

    if (tiedIds.length > 1) {
      startRpsTiebreaker(tiedIds, maxV);
    } else {
      exilePlayerAndContinue(tiedIds[0], '$maxV гол.');
    }
  }

