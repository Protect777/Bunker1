  // ВКЛАДКА 5: ФИНАЛ С РАСЧЁТОМ СКРЫТЫХ ТИРОВ
  Widget _buildFinaleView(GameState s) {
    final survivors = s.players.where((p) => !p.exiled).toList();
    int totalTierPoints = 0;
    int idealCount = 0;
    int terribleCount = 0;

    for (final p in survivors) {
      for (final t in p.traits) {
        totalTierPoints += t.tier;
        if (t.tier == 2) idealCount++;
        if (t.tier == -2) terribleCount++;
      }
    }

    int score = (52 + (totalTierPoints * 4) + s.bunkerBonus).clamp(5, 99);
    String verdict;
    if (score >= 80) {
      verdict =
          'Блестящий отбор! В вашем составе оказалось $idealCount элитных характеристик и почти нет критических слабостей. Убежище процветает!';
    } else if (score >= 50) {
      verdict =
          'Напряжённое выживание! Полезных навыков хватило для запуска систем (элитных карт: $idealCount), но из-за $terribleCount провальных карт не обошлось без кризисов.';
    } else {
      verdict =
          'Катастрофический состав! Вы пустили внутрь слишком много саботажников и бесполезных карт (критических провалов: $terribleCount). Запасы кончились раньше срока!';
    }

    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        _buildCard(
          borderColor: AppColors.green,
          child: Column(
            children: [
              const Text(
                'РАСЧЁТ ВЫЖИВАЕМОСТИ ПО СКРЫТЫМ ТИРАМ',
                style: TextStyle(
                  fontSize: 12,
                  color: AppColors.green,
                  fontWeight: FontWeight.w800,
                ),
              ),
              const SizedBox(height: 6),
              Text(
                '$score%',
                style: const TextStyle(
                  fontSize: 48,
                  fontWeight: FontWeight.w900,
                  color: AppColors.green,
                ),
              ),
              const SizedBox(height: 6),
              Text(
                verdict,
                textAlign: TextAlign.center,
                style: const TextStyle(fontSize: 14.5, height: 1.4),
              ),
            ],
          ),
        ),
        const Padding(
          padding: EdgeInsets.symmetric(vertical: 8),
          child: Text(
            '🎉 Прошли в убежище (все карты вскрыты):',
            style: TextStyle(fontSize: 17, fontWeight: FontWeight.w800),
          ),
        ),
        ...survivors.map(
          (p) => _buildCard(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  '🎉 ${p.name}',
                  style: const TextStyle(
                    fontSize: 17,
                    fontWeight: FontWeight.w800,
                  ),
                ),
                const SizedBox(height: 8),
                ...p.traits.map(
                  (t) => Padding(
                    padding: const EdgeInsets.only(bottom: 4),
                    child: RichText(
                      text: TextSpan(
                        style: const TextStyle(
                          fontSize: 14,
                          color: AppColors.text,
                        ),
                        children: [
                          TextSpan(
                            text: '${t.label}: ',
                            style: const TextStyle(color: AppColors.muted),
                          ),
                          TextSpan(
                            text: t.value,
                            style: const TextStyle(fontWeight: FontWeight.w700),
                          ),
                        ],
                      ),
                    ),
                  ),
                ),
              ],
            ),
          ),
        ),
        if (isHost)
          _buildButton(
            label: 'НОВАЯ ПАРТИЯ В ЭТОЙ КОМНАТЕ',
            bgColor: AppColors.accent,
            textColor: const Color(0xFF111111),
            onTap: hostRestart,
          ),
      ],
    );
  }

  Widget _buildBottomNav() {
    const items = [
      '🪪 Персонаж',
      '👥 Стол',
      '🏰 Убежище',
      '🗳️ Голос/КНБ',
    ];
    return Container(
      decoration: const BoxDecoration(
        color: Color(0xFF121620),
        border: Border(top: BorderSide(color: AppColors.border)),
      ),
      padding: const EdgeInsets.symmetric(vertical: 8, horizontal: 6),
      child: SafeArea(
        top: false,
        child: Row(
          children: List.generate(items.length, (idx) {
            final active = currentTab == idx;
            return Expanded(
              child: InkWell(
                onTap: () => setState(() => currentTab = idx),
                borderRadius: BorderRadius.circular(10),
                child: Container(
                  padding: const EdgeInsets.symmetric(vertical: 8),
                  decoration: BoxDecoration(
                    color: active
                        ? AppColors.accent.withOpacity(0.12)
                        : Colors.transparent,
                    borderRadius: BorderRadius.circular(10),
                  ),
                  child: Text(
                    items[idx],
                    textAlign: TextAlign.center,
                    style: TextStyle(
                      fontSize: 12,
                      fontWeight: FontWeight.w800,
                      color: active ? AppColors.accent : AppColors.muted,
                    ),
                  ),
                ),
              ),
            );
          }),
        ),
      ),
    );
  }

