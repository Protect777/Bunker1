  PlayerModel? getActivePlayer() {
    if (state == null || state!.turnOrder.isEmpty) return null;
    if (state!.currentTurnIdx < 0 ||
        state!.currentTurnIdx >= state!.turnOrder.length) {
      return null;
    }
    final activeId = state!.turnOrder[state!.currentTurnIdx];
    for (final p in state!.players) {
      if (p.id == activeId) return p;
    }
    return null;
  }

  int getEffectiveRequiredCards(PlayerModel? player) {
    if (player == null || state == null) return 0;
    final closedCount = player.traits.where((t) => !t.revealed).length;
    return min(state!.cardsRequired, closedCount);
  }

  // --------------------------------------------------------------------------
  // ОЧЕРЕДЬ ХОДА, БОТЫ И ГОЛОСОВАНИЕ
  // --------------------------------------------------------------------------
  void advanceTurn() {
    if (!isHost || state == null) return;
    state!.currentTurnIdx += 1;
    state!.cardsOpenedInTurn = 0;

    if (state!.currentTurnIdx >= state!.turnOrder.length) {
      startVotingPhase();
    } else {
      final nextP = getActivePlayer();
      state!.lastEvent =
          '👉 Ход перешёл к игроку: ${nextP != null ? nextP.name : ''}';
      broadcastState();
      checkBotTurn();
    }
  }

  void checkBotTurn() {
    if (!isHost || state == null || state!.status != 'GAME') return;
    final activeP = getActivePlayer();
    if (activeP != null && activeP.isBot) {
      botTimer?.cancel();
      botTimer = Timer(const Duration(milliseconds: 850), () {
        if (state == null || state!.status != 'GAME') return;
        final closed = activeP.traits.where((t) => !t.revealed).toList();
        if (closed.isNotEmpty) {
          closed[0].revealed = true;
          state!.cardsOpenedInTurn = 1;
          state!.lastEvent =
              '🤖 ${activeP.name} открыл(а) «${closed[0].label}»: ${closed[0].value}';
        }
        advanceTurn();
      });
    }
  }

  void startVotingPhase() {
    if (!isHost || state == null) return;
    state!.status = 'VOTING';
    state!.votes = {};
    final alive = state!.players.where((p) => !p.exiled).toList();
    for (final p in state!.players) {
      if (p.isBot && !p.exiled) {
        final targets = alive.where((t) => t.id != p.id).toList();
        if (targets.isNotEmpty) {
          state!.votes[p.id] = shuffleList(targets)[0].id;
        }
      }
    }
    state!.lastEvent =
        '🗳️ Все игроки сделали ход в Раунде ${state!.round}! Началось голосование!';
    currentTab = 3;
    broadcastState();
  }

  // --------------------------------------------------------------------------
  // ДУЭЛЬ КАМЕНЬ-НОЖНИЦЫ-БУМАГА ПРИ РАВЕНСТВЕ ГОЛОСОВ
  // --------------------------------------------------------------------------
  void startRpsTiebreaker(List<String> tiedIds, int voteCount) {
    if (state == null) return;
    state!.status = 'RPS';
    final names = tiedIds.map((id) {
      final p = state!.players.where((x) => x.id == id).firstOrNull;
      return p != null ? p.name : id;
    }).join(' vs ');

    state!.rps = RpsState(
      fighters: tiedIds,
      choices: {},
      round: 1,
      summaryText: 'Равенство голосов (по $voteCount)! На арене КНБ: $names',
    );
    state!.lastEvent =
        '⚔️ НИЧЬЯ В ГОЛОСОВАНИИ! $names играют в Камень-Ножницы-Бумага на выбывание!';
    currentTab = 3;

    autoPickRpsForBots();
    broadcastState();
  }

  void autoPickRpsForBots() {
    if (!isHost || state == null || state!.status != 'RPS' || state!.rps == null) {
      return;
    }
    const moves = ['R', 'S', 'P'];
    for (final fid in state!.rps!.fighters) {
      final p = state!.players.where((x) => x.id == fid).firstOrNull;
      if (p != null && p.isBot && !state!.rps!.choices.containsKey(fid)) {
        state!.rps!.choices[fid] = moves[_rng.nextInt(3)];
      }
    }
    checkAndResolveRps();
  }

  void checkAndResolveRps() {
    if (!isHost || state == null || state!.status != 'RPS' || state!.rps == null) {
      return;
    }
    final fighters = state!.rps!.fighters;
    final choices = state!.rps!.choices;

    if (!fighters.every((fid) => choices[fid] != null && choices[fid]!.isNotEmpty)) {
      return;
    }

    const moveIcons = {
      'R': '🪨 Камень',
      'S': '✂️ Ножницы',
      'P': '📄 Бумага',
    };
    final breakdown = fighters.map((fid) {
      final p = state!.players.where((x) => x.id == fid).firstOrNull;
      return '${p != null ? p.name : ''}: ${moveIcons[choices[fid]]}';
    }).join(' | ');

    final uniqueMoves = fighters.map((fid) => choices[fid]!).toSet().toList();

    if (uniqueMoves.length != 2) {
      state!.rps!.round += 1;
      state!.rps!.choices = {};
      state!.rps!.summaryText =
          'Боевая ничья ($breakdown)! Переигровка: Раунд КНБ #${state!.rps!.round}';
      state!.lastEvent =
          '🔄 Ничья в КНБ ($breakdown)! Дуэлянты выбирают снова!';
      autoPickRpsForBots();
      broadcastState();
      return;
    }

    String? losingMove;
    if (uniqueMoves.contains('R') && uniqueMoves.contains('S')) {
      losingMove = 'S';
    } else if (uniqueMoves.contains('S') && uniqueMoves.contains('P')) {
      losingMove = 'P';
    } else if (uniqueMoves.contains('P') && uniqueMoves.contains('R')) {
      losingMove = 'R';
    }

    final losers =
        fighters.where((fid) => choices[fid] == losingMove).toList();

    if (losers.length == 1) {
      exilePlayerAndContinue(losers[0], 'Проиграл(а) дуэль КНБ ($breakdown)');
    } else {
      state!.rps!.fighters = losers;
      state!.rps!.round += 1;
      state!.rps!.choices = {};
      state!.rps!.summaryText =
          'Победители спасены ($breakdown)! Оставшиеся проигравшие продолжают КНБ!';
      state!.lastEvent =
          '⚔️ Часть дуэлянтов спаслась! Финальный раунд КНБ между проигравшими!';
      autoPickRpsForBots();
      broadcastState();
    }
  }

  void exilePlayerAndContinue(String exiledId, String reasonText) {
    if (state == null) return;
    final victim = state!.players.where((p) => p.id == exiledId).firstOrNull;
    if (victim != null) victim.exiled = true;

    for (final p in state!.players) {
      p.voteShield = false;
      p.doubleVote = false;
    }
    state!.rps = null;

    final alive = state!.players.where((p) => !p.exiled).toList();
    if (alive.length <= state!.capacity) {
      state!.status = 'FINALE';
      for (final p in alive) {
        for (final t in p.traits) {
          t.revealed = true;
        }
      }
      state!.lastEvent =
          '🚪 ${victim != null ? victim.name : ''} изгнан(а) ($reasonText). Врата убежища запечатаны!';
      broadcastState();
    } else {
      state!.round += 1;
      state!.status = 'GAME';
      state!.votes = {};
      state!.turnOrder = alive.map((p) => p.id).toList();
      state!.currentTurnIdx = 0;
      state!.cardsRequired = 1;
      state!.cardsOpenedInTurn = 0;
      final firstP = getActivePlayer();
      state!.lastEvent =
          '💀 Изгнан(а) ${victim != null ? victim.name : ''} ($reasonText). Начался Раунд ${state!.round}! Ходит ${firstP != null ? firstP.name : ''}.';
      currentTab = 0;
      broadcastState();
      checkBotTurn();
    }
  }

  // --------------------------------------------------------------------------
  // ОБРАБОТКА ДЕЙСТВИЙ ИГРОКОВ И 24 СПЕЦКАРТ
  // --------------------------------------------------------------------------
  void handleClientAction(Map<String, dynamic> act) {
    if (!isHost || state == null) return;
    final type = act['type'] as String?;

    if (type == 'JOIN') {
      final pMap = Map<String, dynamic>.from(act['player'] as Map);
      final pid = pMap['id'] as String;
      final pname = pMap['name'] as String;
      if (!state!.players.any((p) => p.id == pid)) {
        state!.players.add(PlayerModel(id: pid, name: pname));
        state!.lastEvent = '👋 $pname присоединился к комнате!';
      }
    } else if (type == 'LEAVE') {
      final pid = act['playerId'] as String?;
      final leaver = state!.players.where((p) => p.id == pid).firstOrNull;
      if (leaver != null) {
        state!.lastEvent = '🚪 ${leaver.name} покинул(а) игру.';
        if (state!.status == 'LOBBY') {
          state!.players.removeWhere((p) => p.id == pid);
        } else {
          leaver.exiled = true;
          final activeP = getActivePlayer();
          if (activeP != null && activeP.id == pid) {
            advanceTurn();
            return;
          }
        }
      }
    } else if (type == 'CUSTOM_CARD') {
      final text = (act['text'] ?? '') as String;
      if (text.isNotEmpty) {
        state!.customCards.add(text);
        state!.lastEvent = '➕ В колоду добавлена своя карточка!';
      }
    } else if (type == 'REVEAL') {
      if (state!.status != 'GAME') return;
      final activeP = getActivePlayer();
      final pid = act['playerId'] as String?;
      final traitIdx = (act['traitIdx'] as num?)?.toInt() ?? -1;
      if (activeP == null || activeP.id != pid) return;

      final req = getEffectiveRequiredCards(activeP);
      if (state!.cardsOpenedInTurn >= req) return;

      if (traitIdx >= 0 &&
          traitIdx < activeP.traits.length &&
          !activeP.traits[traitIdx].revealed) {
        activeP.traits[traitIdx].revealed = true;
        state!.cardsOpenedInTurn += 1;
        state!.lastEvent =
            '📢 ${activeP.name} открыл(а) «${activeP.traits[traitIdx].label}»: ${activeP.traits[traitIdx].value}';
      }
    } else if (type == 'END_TURN') {
      if (state!.status != 'GAME') return;
      final activeP = getActivePlayer();
      final pid = act['playerId'] as String?;
      if (activeP != null && activeP.id == pid) {
        final req = getEffectiveRequiredCards(activeP);
        if (state!.cardsOpenedInTurn >= req) {
          advanceTurn();
          return;
        }
      }
    } else if (type == 'USE_ACTION') {
      final pid = act['playerId'] as String?;
      final p = state!.players.where((x) => x.id == pid).firstOrNull;
      if (p != null && !p.actionUsed && !p.exiled) {
        p.actionUsed = true;
        executeSpecialAction(p);
      }
    } else if (type == 'VOTE') {
      if (state!.status == 'VOTING') {
        final voterId = act['voterId'] as String;
        final targetId = act['targetId'] as String;
        state!.votes[voterId] = targetId;
      }
    } else if (type == 'RPS_MOVE') {
      final pid = act['playerId'] as String;
      final move = act['move'] as String;
      if (state!.status == 'RPS' &&
          state!.rps != null &&
          state!.rps!.fighters.contains(pid)) {
        state!.rps!.choices[pid] = move;
        checkAndResolveRps();
        return;
      }
    }

    broadcastState();
  }

  void executeSpecialAction(PlayerModel p) {
    if (state == null) return;
    final id = p.action.id;
    final m = state!.mode;
    final enemies =
        state!.players.where((x) => x.id != p.id && !x.exiled).toList();

    if (id == 'heal') {
      final c = drawSingleByTier('health', 2, m);
      p.traits[2] = TraitCard(
          label: p.traits[2].label, value: c.value, tier: 2, revealed: true);
      state!.lastEvent = '💉 ${p.name} применил(а) Панацею: ${c.value}!';
    } else if (id == 're_prof') {
      final c = drawSingleByTier('prof', 2, m);
      p.traits[0] = TraitCard(
          label: p.traits[0].label, value: c.value, tier: 2, revealed: true);
      state!.lastEvent = '🎓 ${p.name} прошёл переподготовку: ${c.value}!';
    } else if (id == 're_lug') {
      final c = drawSingleByTier('luggage', 2, m);
      p.traits[4] = TraitCard(
          label: p.traits[4].label, value: c.value, tier: 2, revealed: true);
      state!.lastEvent = '🧳 ${p.name} открыл элитный тайник: ${c.value}!';
    } else if (id == 'spy_random' && enemies.isNotEmpty) {
      final t = shuffleList(enemies)[0];
      final closed = t.traits.where((x) => !x.revealed).toList();
      if (closed.isNotEmpty) {
        closed[0].revealed = true;
        state!.lastEvent =
            '🕵️ ${p.name} просканировал(а) ${t.name}: ${closed[0].value}!';
      }
    } else if (id == 'spy_health' && enemies.isNotEmpty) {
      final targets = shuffleList(enemies).take(2);
      for (final t in targets) {
        if (t.traits.length > 2) t.traits[2].revealed = true;
      }
      state!.lastEvent =
          '🩺 ${p.name} провёл принудительный медосмотр соперников!';
    } else if (id == 'spy_prof' && enemies.isNotEmpty) {
